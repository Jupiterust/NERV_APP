/* ============================================================================
 * 【0】Modbus 基础
 * ============================================================================
 *
 * ① Modbus 只有 4 种数据区，读写权限由规范规定，不是本工程的限制：
 *
 *      数据区        位宽    权限    读功能码   写功能码        本工程放什么
 *      ---------------------------------------------------------------------
 *      线圈          1 位    读写    FC01      FC05/FC15       开关（启停自动上报…）
 *      离散输入      1 位    只读    FC02      —               状态位（超限、断线…）
 *      保持寄存器    16 位   读写    FC03      FC06/FC16       参数（变比、阈值、DAC…）
 *      输入寄存器    16 位   只读    FC04      —               测量值（电压、温度…）
 *
 *    官方点表里"可写"的量必须放保持寄存器或线圈，"只读"的量放输入寄存器或离散输入。
 *    放错区的后果是主站按它的功能码读不到 / 写不进。
 *
 * ② 一个寄存器 16 位（0~65535），float 和 32 位整数占 2 个连续寄存器。本文件里注释
 *    标 float / u32 的，下一个可用地址要 +2 而不是 +1。两个寄存器的高低半边顺序
 *    即字序问题，见【4】。
 *
 * ③ 地址有两种写法，混用的表现是整体差 1 或整体差一大截：
 *
 *      线上地址(协议地址, Base 0)：报文里真正传输的数字，从 0 开始
 *      PLC 地址  (Base 1, 5 位)  ：40001 / 30001 / 10001 / 00001 这种写法
 *
 *      换算：  保持寄存器 40001 ↔ 线上 0     （PLC 地址减 40001）
 *              输入寄存器 30001 ↔ 线上 0     （PLC 地址减 30001）
 *              离散输入   10001 ↔ 线上 0     （PLC 地址减 10001）
 *              线圈       00001 ↔ 线上 0     （PLC 地址减 1）
 *
 *    本文件里所有 #define 填的都是线上地址。Modbus Poll 的 Address 栏默认也显示
 *    线上地址，勾了 "Display → PLC Addresses (Base 1)" 才变成 5 位写法。
 *
 * ④ 一帧 Modbus RTU 报文长这样（例：读从站 1 的 CH0 当前值 = 输入寄存器 0 起 2 个）：
 *
 *        01    04    00 00    00 02    71 CB
 *        │     │     │        │        └── CRC16 校验（低字节在前，工具会自动算）
 *        │     │     │        └────────── 寄存器个数 = 2（float 占 2 个）
 *        │     │     └─────────────────── 起始地址 = 0（线上地址）
 *        │     └───────────────────────── 功能码 04 = 读输入寄存器
 *        └─────────────────────────────── 从站地址 = 1
 *
 *      从站应答： 01 04 04 <4 个字节的数据> CRC16
 *                       └ 字节数 = 2 个寄存器 × 2 = 4
 *
 *    Modbus ASCII 是同样内容换成十六进制文本，前加 ':'、后加回车换行，校验从
 *    CRC16 换成 LRC。本工程两种都支持并自动识别，见【2】。
 *
 * ⑤ 从站回的功能码 = 请求功能码 + 0x80 表示异常，后面 1 个字节是异常码：
 *        01 = 非法功能码（本机没实现这个 FC）
 *        02 = 非法数据地址（超出点表范围，多半是地址填错或超过表容量）
 *        03 = 非法数据值  （寄存器个数为 0 或太大）
 *        04 = 从站设备故障
 */


/* ============================================================================
 * 【1】现场速查 —— 拿到官方点表照着做
 * ============================================================================
 *
 * ─ 场景 A：官方点表的地址和默认表不一样（最常见）────────────────────────────
 *     只改【5】~【8】里对应那一行的数字。例如官方要求 CH0 当前值放输入寄存器 10：
 *         #define MB_IREG_CH0_VALUE    10
 *     float / u32 占 2 个寄存器，注意别和下一项撞地址，撞了后写的会覆盖前一个。
 *
 * ─ 场景 B：官方点表整体平移 ──────────────────────────────────────────────────
 *     例：官方要求保持寄存器从 40101 开始（线上地址 100），相对顺序和默认表一致。
 *     不用逐行改，只改【3】里一个数：
 *         #define MB_HREG_ADDR_BASE    100
 *     官方点表从 1 开始编号时，把基址改成 1。
 *
 * ─ 场景 C：官方要放大 N 倍的整数而不是 float ────────────────────────────────
 *     默认表里已有整数镜像（MB_IREG_CH0_SCALED 等），把地址改到官方要求的位置，
 *     倍数在【4】改：#define MB_SCALE_CH0  100.0f，要 ×10 就写 10.0f。
 *     float 那几个地址留着不影响，官方不读即可。
 *
 * ─ 场景 D：能读到但数值离谱 / 乱跳 ──────────────────────────────────────────
 *     多半是 float 字序对不上，改【4】的 MB_FLOAT_BYTE_ORDER，4 选 1 逐个试。
 *
 * ─ 场景 E：完全读不到，主站一直超时 ──────────────────────────────────────────
 *     按顺序查：从站地址（【2】MB_FORCE_SLAVE_ADDR）→ 波特率 → A/B 线接反 →
 *     协议模式（【2】MB_DEFAULT_PROTOCOL_MODE）。详见【10】。
 *
 * ─ 场景 F：官方点表里有本机没有的量 ────────────────────────────────────────
 *     三步：
 *       1) 本文件【5】~【8】里加一行地址定义：
 *                 #define MB_IREG_MY_NEW      50      // float : 我的新量
 *       2) modbus_data_map.c 顶部的编译期越界检查里加一行：
 *                 MB_CHK(ireg_my_new,  MB_IREG_MY_NEW,  2, REG_INPUT_SIZE);
 *                 最后一个参数按数据区选：输入寄存器 REG_INPUT_SIZE、保持寄存器
 *                 REG_HOLD_SIZE、线圈 REG_COILS_SIZE、离散输入 REG_DISC_SIZE；
 *                 倒数第二个是占几个寄存器，float/u32 填 2，u16 填 1
 *       3) modbus_data_map.c 的 Modbus_SyncRegsFromDevice() 里加一行搬运：
 *                 reg_write_float(REG_INPUT_BUF, MB_IREG_MY_NEW, 我的变量);
 *                 整数用 REG_INPUT_BUF[MB_IREG_MY_NEW] = 我的变量;
 *                 u32 用 reg_write_u32(...)，缩放整数用 reg_write_scaled(...)
 *     可写的量还要在 Modbus_ApplyHoldingRegs() / Modbus_ApplyCoils() 里加一行反向
 *     搬运，那两个函数里每一项都是现成例子。
 *
 * ─ 场景 G：官方地址很大（比如保持寄存器 200）────────────────────────────────
 *     表容量不够会直接编译报错，改大【3】里的 MB_HREG_COUNT 即可。
 *     每加 1 个寄存器多占 2 字节 RAM，本机有 192KB。
 *
 * 地址填错或超容量会在编译期报错，不会到现场才跑飞。报错形式是
 * "size of array is negative"，数组名 mb_chk_xxx 里的 xxx 就是出问题的那一项，
 * 把它的地址改小或把表容量改大即可。
 */


/* ============================================================================
 * 【2】通信身份：从站地址 / 协议模式
 * ============================================================================ */

/* 强制从站地址。
 *   0     = 用 flash 里存着的地址（开机 main.c 从 param_get_mb_addr() 读，
 *           也就是上一次通过保持寄存器或自定义协议改过的值）—— 默认
 *   1~247 = 强制用这个地址，忽略 flash 里的值
 *
 * 官方指定站号时直接在这里填上编译下载，这样 flash 里残留的调试地址不会捣乱
 *（"昨天还能通，今天主站找不到设备"多半就是这个原因）。
 *
 * 这里只决定开机时用哪个地址。填了非 0 之后主站仍可通过保持寄存器
 * MB_HREG_MB_SLAVE_ADDR 在运行中改地址，只是重启后回到这里钉死的值。 */
#define MB_FORCE_SLAVE_ADDR         1

/* 开机默认协议模式（运行中也可以直接改全局变量 Protocol_mode）：
 *   1 = 只认自定义协议（A5B6 帧）
 *   2 = 只认 Modbus RTU（二进制）
 *   3 = 只认 Modbus ASCII（':' 开头的十六进制文本）
 *   4 = 自动识别（默认）：帧以 ASCII "A5B6" 开头当自定义协议，否则当 Modbus；
 *       Modbus 内部再按有没有 ':' 分 ASCII / RTU
 * 只在自动识别误判、需要排除干扰时才改成 2 或 3。 */
#define MB_DEFAULT_PROTOCOL_MODE    4

/* 总线上有 Modbus 主站时暂停自定义协议的定时上报
 *   1 = 暂停（默认）
 *   0 = 不暂停，两个协议同时往总线上发
 *
 * Modbus 规范里从站只能被动应答。定时上报是自定义协议的功能，一旦开着，本机就成了
 * 总线上第二个主动发送者，和主站的轮询帧在半双工 485 上撞车，双方字节互相破坏：
 *   ① 主站看到应答后面粘着一截数据，那是紧跟着发出去的上报帧
 *   ② 主站的轮询被撞坏 → 本机 CRC 不过 → 按规范静默丢弃 → 主站超时无应答
 *   ③ 两个周期接近但不相等，相位每秒漂移几毫秒，所以是周期性发作：撞几秒、正常
 *      一两分钟、再撞，容易被误判成偶发故障
 * 另外发送期间接收中断是关着的（见 bsp_rs485.c），发上报帧的那 20 多毫秒里听不到
 * 主站说话，这一次轮询必丢。
 *
 * 判定规则（不需要定时器）：
 *   收到一帧校验通过的 Modbus 报文 → 认定有 Modbus 主站 → 暂停上报
 *   之后收到一帧 A5B6 开头的报文   → 认为切回自定义协议 → 恢复上报
 *   Protocol_mode 被强制成 2 或 3  → 一直暂停
 * 暂停期间 Regular_reporting_Flag 仍是 1，输入寄存器和线圈里的"自动上报中"状态
 * 不变，只是不往总线上发帧。 */
#define MB_SUPPRESS_AUTO_REPORT_ON_MODBUS   1

/* 波特率编码表：主站读写波特率用的是码不是数值本身，这套码沿用自定义协议
 * 4.5.1(7) 的定义。官方 Modbus 点表规定了别的编码就改这 4 个数。
 * 改波特率会等这一帧应答发完才真正切换，否则主站收不到确认。 */
#define MB_BAUD_CODE_4800           0x11
#define MB_BAUD_CODE_9600           0x12
#define MB_BAUD_CODE_19200          0x13
#define MB_BAUD_CODE_115200         0x14
#define MB_BAUD_CODE_DEFAULT        MB_BAUD_CODE_19200  /* 波特率不在表里时回读的码 */


