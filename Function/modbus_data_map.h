/* ============================================================================
 * 【4】数据编码：float 字序 / 缩放倍数
 * ============================================================================ */

/* float 与 u32 的字序：占 2 个寄存器的量，两个寄存器怎么排。
 * 设 IEEE754 标准字节顺序是 A B C D（A 最高）：
 *
 *   0 = AB CD   高字在前，寄存器内不交换   Modbus 标准写法，默认
 *   1 = CD AB   低字在前（字交换）         很多 PLC / 国产仪表用这种
 *   2 = BA DC   高字在前，寄存器内字节交换
 *   3 = DC BA   低字在前，寄存器内字节交换
 *
 * 和 Modbus Poll 的 Display → Float 格式一一对应。读到的数值离谱（1e-38、几百万）
 * 或小数点乱跳基本都是这里不对，4 个挨个试。
 * 改这一个数，所有 float 和 u32（含时间戳、版本号、告警时间戳）一起变，读和写
 * 用同一套规则，不会出现写进去和读出来不一致。 */
#define MB_FLOAT_BYTE_ORDER         0

/* 缩放倍数：官方点表要求放大 N 倍的 16 位整数时用。
 * 例：CH0 实测 2.35V，倍数 100 → 寄存器里是 235，主站除以 100 还原。
 * 结果有饱和保护（-32768 ~ 32767），变比调大也不会溢出翻成负数。
 * 要 ×10 就写 10.0f，×1000 写 1000.0f，注意保留小数点和 f。 */
#define MB_SCALE_CH0                100.0f   /* CH0 当前值      默认 ×100 */
#define MB_SCALE_CH1                100.0f   /* CH1 当前值      默认 ×100 */
#define MB_SCALE_CH2                10.0f    /* CH2 PT100 温度  默认 ×10  */
#define MB_SCALE_I0                 100.0f   /* 4~20mA 电流     默认 ×100 */
#define MB_SCALE_V0                 100.0f   /* 0~10V 通道 0    默认 ×100 */
#define MB_SCALE_V1                 100.0f   /* 0~10V 通道 1    默认 ×100 */


/* ============================================================================
 * 【5】点表本体 A —— 输入寄存器（功能码 FC04，只读）
 * ----------------------------------------------------------------------------
 * 主站用 FC04 读，规范规定只读，官方要求可写的量不能放这里。
 * 注释里 float / u32 占 2 个寄存器，u16 / i16 占 1 个。
 * ============================================================================ */

/* --- 实时采样值（float，工程量，已经乘过变比） --- */
#define MB_IREG_CH0_VALUE           0   /* float : CH0 当前值（已乘变比）      */
#define MB_IREG_CH1_VALUE           2   /* float : CH1 当前值（已乘变比）      */
#define MB_IREG_CH2_TEMP            4   /* float : CH2 PT100 温度，单位 ℃      */
#define MB_IREG_CH0_RAW             6   /* float : CH0 原始电压（未乘变比）V    */
#define MB_IREG_CH1_RAW             8   /* float : CH1 原始电压（未乘变比）V    */

/* --- 同一批数据的缩放整数镜像，官方给整数表时改这几个的地址 ---
 *     倍数在【4】的 MB_SCALE_* 里改。和上面的 float 是同一份源数据，
 *     两套并存不冲突。 */
#define MB_IREG_CH0_SCALED         10   /* i16 : CH0 当前值 × MB_SCALE_CH0     */
#define MB_IREG_CH1_SCALED         11   /* i16 : CH1 当前值 × MB_SCALE_CH1     */
#define MB_IREG_CH2_SCALED         12   /* i16 : CH2 温度   × MB_SCALE_CH2     */

/* --- 时间与版本 --- */
#define MB_IREG_TIMESTAMP          13   /* u32 : RTC 秒级时间戳（Unix 秒）      */
#define MB_IREG_FW_VERSION         15   /* u32 : 固件版本号，如 0x02000100      */

/* --- 运行状态（都是 1 个寄存器的整数） --- */
#define MB_IREG_AUTO_FLAG          17   /* u16 : 正在定时自动上报 = 1           */
#define MB_IREG_ALARM_MODE         18   /* u16 : 告警模式 1=主动上报 2=仅记录   */
#define MB_IREG_REPORT_INTVL       19   /* u16 : 上报间隔码 1/2/3，见【9】      */
#define MB_IREG_BAUD_CODE          20   /* u16 : 当前波特率码，见【2】          */
