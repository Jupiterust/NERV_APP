/* ============================================================================
 * 【10】排错速查
 * ============================================================================
 *
 * 症状：主站一直超时，什么都读不到
 *   1. 从站地址对不上，最常见。用【2】的 MB_FORCE_SLAVE_ADDR 钉死，或用 Modbus Poll
 *      的扫描功能逐个试。本机当前地址在输入寄存器 MB_IREG_MB_SLAVE_ADDR 里，但要先
 *      能通才读得到，钉死更快。
 *   2. 波特率对不上。波特率存在 flash 里，可能是上次调试改过的。逐个试
 *      4800/9600/19200/115200，或用自定义协议连上去改回来，或调
 *      param_restore_defaults() 恢复出厂（19200）。串口参数固定 8 位 / 无校验 / 1 停止位。
 *   3. A/B 两根线接反，现象和地址不对一样，换一下最快。
 *   4. 协议模式被锁死，【2】的 MB_DEFAULT_PROTOCOL_MODE 应该是 4。
 *   5. 主站响应超时太短。本机写参数要擦 flash，清告警记录最长阻塞 400ms，
 *      建议把 Response Timeout 设到 1000ms 以上。
 *
 * 症状：能通，但回的是异常码
 *   0x02 非法数据地址 → 地址超出点表范围。检查地址是不是超过【3】的表容量，
 *                       或者【3】的基址设了但主站没跟着改。
 *   0x03 非法数据值   → 请求的寄存器个数为 0 或太大。
 *   0x01 非法功能码   → 本机实现了 FC01/02/03/04/05/06/07/08/15/16/17/23，
 *                       别的功能码没实现。
 *
 * 症状：数值不对
 *   数值离谱 / 小数点乱跳 → float 字序，改【4】的 MB_FLOAT_BYTE_ORDER，4 个试一遍
 *   数值差 100 倍         → 主站按整数读了缩放寄存器，或【4】的倍数不对
 *   整体错开 1 个地址     → PLC 地址(Base 1)和线上地址(Base 0)混了，见【0】③，
 *                           检查 Modbus Poll 的 Display 菜单勾没勾 PLC Addresses
 *   全是 0                → 读的是没用到的空地址，对一下【11】的总表
 *   CH2 温度不刷新        → 温度取的是缓存值，刷新由主循环负责，不是点表的问题
 *
 * 症状：读多个寄存器时最后几个是乱的
 *   跨过了两个不相邻的字段（比如从 33 一次读到 45），中间未定义的地址内容是 0，
 *   不是故障，按【11】的总表分段读即可。
 */


